# Use nest to evaluate p(x) = 1 - x + x^2 - x^3 + ... + x^98 - x^99 at x = 1.00001

import numpy as np

def polyval_nested(c, x):
  d = np.size(c)
  px = c[d - 1]
  for i in range(d - 2, -1, -1 ):
    px = px * x + c[i]
  return px

x = 1.00001
d = 99
c = np.ones([d+1])
px1 = polyval_nested(c, x)
print(px1)

# Simplified version
px2 = ((x ** (d + 1)) - 1) / (x - 1)
